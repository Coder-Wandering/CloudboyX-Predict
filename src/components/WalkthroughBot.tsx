export const WalkthroughBot: React.FC<WalkthroughBotProps> = ({
  activeView,
  onSelectView,
  onOpenTrainingDocs,
  onOpenPortfolio,
  onOpenIngestion,
  onOpenPythonScript,
  activeEventTitle,
}) => {
  const [isOpen, setIsOpen] = useState(false);
  const [activeTab, setActiveTab] = useState<'directory' | 'tour' | 'ask'>('directory');
  const [selectedSection, setSelectedSection] = useState<SectionGuide | null>(SECTION_GUIDES[0]);
  const [tourStepIdx, setTourStepIdx] = useState<number>(0);
  const [isTourActive, setIsTourActive] = useState<boolean>(false);

  // Chatbot states
  const [chatMessages, setChatMessages] = useState<ChatMessage[]>([
    {
      id: 'welcome',
      sender: 'bot',
      text: `Hello! I'm PredictaBot, your interactive walkthrough assistant. I can guide you through any section of CloudboyX Predict—including the new Webhook Studio, Backtest Engine, HMAC Security, 3-Check Volatility, and Kelly sizing. How can I assist you today?`,
    },
  ]);
  const [inputQuestion, setInputQuestion] = useState('');
  const [isBotThinking, setIsBotThinking] = useState(false);

  const messagesEndRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [chatMessages, isBotThinking]);

  // Handle navigating and spotlighting a DOM element
  const handleJumpToSection = (guide: SectionGuide) => {
    if (activeView !== guide.view) {
      onSelectView(guide.view);
    }

    // Allow time for view switch then scroll & highlight
    setTimeout(() => {
      // If jumping to specific webhook modes, trigger the corresponding tab if needed
      if (guide.id === 'webhook-backtest') {
        const backtestTabBtn = document.getElementById('connect-mode-backtest-btn');
        if (backtestTabBtn) backtestTabBtn.click();
      } else if (guide.id === 'webhook-health') {
        const healthTabBtn = document.getElementById('connect-mode-health-btn');
        if (healthTabBtn) healthTabBtn.click();
      } else if (guide.id === 'map-connectors') {
        const connTabBtn = document.getElementById('connect-mode-connectors-btn');
        if (connTabBtn) connTabBtn.click();
      } else if (guide.id === 'webhook-security') {
        const secBtn = document.getElementById('webhook-open-security-credentials-btn');
        if (secBtn) {
          secBtn.click();
          return;
        }
      } else if (guide.id === 'training-pdf') {
        onOpenTrainingDocs();
        return;
      }

      let targetEl = document.getElementById(guide.domId);
      if (!targetEl) {
        // Fallback checks
        if (guide.id === 'paper-portfolio') {
          onOpenPortfolio();
          return;
        }
        if (guide.id === 'python-pipeline') {
          onOpenPythonScript();
          return;
        }
      }

      if (targetEl) {
        targetEl.scrollIntoView({ behavior: 'smooth', block: 'center' });
        // Add spotlight animation class
        targetEl.classList.add('ring-4', 'ring-[#0077b6]', 'ring-offset-4', 'transition-all', 'duration-500');
        setTimeout(() => {
          targetEl?.classList.remove('ring-4', 'ring-[#0077b6]', 'ring-offset-4');
        }, 2500);
      }
    }, 180);
  };

  // Tour step navigation
  const handleTourStep = (newIdx: number) => {
    if (newIdx < 0 || newIdx >= TOUR_STEPS.length) return;
    setTourStepIdx(newIdx);
    const step = TOUR_STEPS[newIdx];

    if (activeView !== step.view) {
      onSelectView(step.view);
    }

    setTimeout(() => {
      const el = document.getElementById(step.domId);
      if (el) {
        el.scrollIntoView({ behavior: 'smooth', block: 'center' });
        el.classList.add('ring-4', 'ring-[#0077b6]', 'ring-offset-4', 'transition-all', 'duration-500');
        setTimeout(() => {
          el.classList.remove('ring-4', 'ring-[#0077b6]', 'ring-offset-4');
        }, 2000);
      }
    }, 180);
  };

  const handleAskQuestion = async (queryText?: string) => {
    const question = (queryText || inputQuestion).trim();
    if (!question) return;

    const userMsg: ChatMessage = {
      id: `user-${Date.now()}`,
      sender: 'user',
      text: question,
    };

    setChatMessages((prev) => [...prev, userMsg]);
    setInputQuestion('');
    setIsBotThinking(true);

    try {
      const res = await fetch('/api/guide-bot', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          question,
          currentSection: selectedSection?.title || 'General Overview',
          activeEvent: activeEventTitle || 'Active Prediction Event',
          history: chatMessages.slice(-4),
        }),
      });

      const data = await res.json();
      const botReply = data.reply || "I'm ready to walk you through any section of CloudboyX Predict!";

      // Identify suggested action if query matches a section
      let suggestedAction: ChatMessage['suggestedAction'] = undefined;
      const qLower = question.toLowerCase();
      if (qLower.includes('backtest') || qLower.includes('simulate') || qLower.includes('replay')) {
        suggestedAction = { label: 'Open Backtest Engine', sectionId: 'webhook-backtest', view: 'erp_connector' };
      } else if (qLower.includes('webhook') || qLower.includes('erp') || qLower.includes('dispatch') || qLower.includes('edi') || qLower.includes('iso 20022')) {
        suggestedAction = { label: 'Jump to Webhook Studio', sectionId: 'webhook-studio', view: 'erp_connector' };
      } else if (qLower.includes('hmac') || qLower.includes('secret') || qLower.includes('security') || qLower.includes('token') || qLower.includes('credentials')) {
        suggestedAction = { label: 'View Security Credentials', sectionId: 'webhook-security', view: 'erp_connector' };
      } else if (qLower.includes('health') || qLower.includes('latency') || qLower.includes('audit')) {
        suggestedAction = { label: 'View Webhook Health Dashboard', sectionId: 'webhook-health', view: 'erp_connector' };
      } else if (qLower.includes('connector') || qLower.includes('map') || qLower.includes('shopify') || qLower.includes('amazon')) {
        suggestedAction = { label: 'View Protection Connectors', sectionId: 'map-connectors', view: 'erp_connector' };
      } else if (qLower.includes('pdf') || qLower.includes('manual') || qLower.includes('print') || qLower.includes('cheatsheet')) {
        suggestedAction = { label: 'Open PDF Documentation', sectionId: 'training-pdf', view: 'market_analyzer' };
      } else if (qLower.includes('studio') || qLower.includes('model') || qLower.includes('regression')) {
        suggestedAction = { label: 'Jump to Model Studio', sectionId: 'model-studio', view: 'model_studio' };
      } else if (qLower.includes('volatility') || qLower.includes('arrow') || qLower.includes('check')) {
        suggestedAction = { label: 'Jump to 3-Check Volatility', sectionId: 'price-volatility', view: 'market_analyzer' };
      } else if (qLower.includes('kelly') || qLower.includes('sizing') || qLower.includes('ev') || qLower.includes('attribution') || qLower.includes('variance')) {
        suggestedAction = { label: 'Jump to Kelly & Risk Attribution', sectionId: 'kalshi-calculator', view: 'market_analyzer' };
      } else if (qLower.includes('paper') || qLower.includes('trade') || qLower.includes('bankroll')) {
        suggestedAction = { label: 'Open Paper Portfolio', sectionId: 'paper-portfolio', view: 'market_analyzer' };
      } else if (qLower.includes('export') || qLower.includes('save') || qLower.includes('json') || qLower.includes('download')) {
        suggestedAction = { label: 'Jump to Odds Overview & Export', sectionId: 'odds-overview', view: 'market_analyzer' };
      }

      setChatMessages((prev) => [
        ...prev,
        {
          id: `bot-${Date.now()}`,
          sender: 'bot',
          text: botReply,
          suggestedAction,
        },
      ]);
    } catch (err) {
      setChatMessages((prev) => [
        ...prev,
        {
          id: `bot-${Date.now()}`,
          sender: 'bot',
          text: `Here is the key takeaway: Always verify statistical edge (E = P_calibrated - Market Price). If edge is positive, allocate capital according to Half-Kelly to compound safely without ruin risk!`,
        },
      ]);
    } finally {
      setIsBotThinking(false);
    }
  };

  const presetQuestions = [
    'How do I run a webhook backtest simulation?',
    'How does HMAC-SHA256 signature verification work?',
    'What webhook formats are supported (JSON, ISO XML, EDI)?',
    'How do I interpret Green & Red arrows?',
    'Why should I use Half-Kelly sizing?',
    'How do MAP Price Protection Connectors work?',
    'How do I export and save my research data?',
    'How do I download the PDF Operator Manuals?',
  ];

  return (
    <>
      {/* Floating Launcher Button */}
      {!isOpen && (
        <div className="fixed bottom-5 right-5 z-40 flex items-center space-x-2">
          {/* Subtle Attention Prompt Pill */}
          <div
            onClick={() => setIsOpen(true)}
            className="hidden sm:flex items-center space-x-1.5 px-3 py-1.5 rounded-full bg-white/95 backdrop-blur-md shadow-md border border-[#90e0ef] text-[#03045e] text-xs font-semibold hover:border-[#00b4d8] hover:bg-[#caf0f8]/40 transition-all cursor-pointer group"
          >
            <Compass className="w-3.5 h-3.5 text-[#0077b6] group-hover:rotate-45 transition-transform" />
            <span>Walk through any section</span>
          </div>

          {/* Main Bot Floating Bubble */}
          <button
            id="walkthrough-bot-launcher-btn"
            onClick={() => setIsOpen(true)}
            className="relative p-3 sm:p-3.5 rounded-2xl bg-[#03045e] text-white shadow-xl hover:bg-[#0077b6] hover:scale-105 active:scale-95 transition-all cursor-pointer flex items-center justify-center group"
            aria-label="Open Interactive Walkthrough Bot"
            title="Open Interactive Walkthrough Bot (PredictaBot)"
          >
            <div className="relative">
              <Sparkles className="w-6 h-6 sm:w-7 sm:h-7 text-[#caf0f8] group-hover:rotate-12 transition-transform" />
              <span className="absolute -top-1 -right-1 w-3 h-3 rounded-full bg-[#00b4d8] border-2 border-[#03045e] animate-pulse"></span>
            </div>
          </button>
        </div>
      )}

      {/* Expanded Walkthrough Assistant Panel */}
      {isOpen && (
        <div
          id="walkthrough-bot-panel"
          className="fixed bottom-4 right-4 sm:bottom-6 sm:right-6 z-50 w-[94vw] sm:w-[460px] max-h-[88vh] bg-white rounded-2xl shadow-2xl border border-[#90e0ef] flex flex-col overflow-hidden animate-fadeIn font-sans"
        >
          {/* Bot Header */}
          <div className="px-4 py-3.5 bg-[#03045e] text-white flex items-center justify-between">
            <div className="flex items-center space-x-2.5">
              <div className="w-8 h-8 rounded-xl bg-gradient-to-tr from-[#0077b6] to-[#00b4d8] flex items-center justify-center text-white shadow-xs">
                <Sparkles className="w-4 h-4 text-[#caf0f8]" />
              </div>
              <div>
                <div className="flex items-center space-x-1.5">
                  <span className="font-extrabold text-sm tracking-tight text-[#caf0f8]">PredictaBot</span>
                  <span className="px-1.5 py-0.2 rounded bg-[#00b4d8]/20 text-[#caf0f8] text-[10px] font-bold font-mono">
                    ONLINE
                  </span>
                </div>
                <div className="text-[11px] text-[#90e0ef]">
                  Interactive Platform &amp; Webhook Walkthrough Guide
                </div>
              </div>
            </div>

            <div className="flex items-center space-x-1">
              <button
                onClick={() => {
                  window.open('/api/docs/pdf/all', '_blank');
                }}
                className="p-1.5 text-[#caf0f8] hover:text-white rounded-lg hover:bg-[#0077b6]/50 transition-colors cursor-pointer"
                title="Download complete instruction & training manual as PDF"
              >
                <Printer className="w-4 h-4" />
              </button>
              <button
                onClick={() => {
                  onOpenTrainingDocs();
                  setIsOpen(false);
                }}
                className="p-1.5 text-[#90e0ef] hover:text-white rounded-lg hover:bg-[#0077b6]/50 transition-colors cursor-pointer"
                title="Open Official Documentation & Training Center"
              >
                <BookOpen className="w-4 h-4" />
              </button>
              <button
                onClick={() => setIsOpen(false)}
                className="p-1.5 text-[#90e0ef] hover:text-white rounded-lg hover:bg-[#0077b6]/50 transition-colors cursor-pointer"
                aria-label="Minimize Walkthrough Bot"
              >
                <X className="w-4 h-4" />
              </button>
            </div>
          </div>

          {/* Navigation Sub-Tabs */}
          <div className="px-3 pt-2 pb-1.5 bg-[#caf0f8]/20 border-b border-stone-200 flex items-center justify-between text-xs">
            <div className="flex items-center space-x-1">
              <button
                onClick={() => {
                  setActiveTab('directory');
                  setIsTourActive(false);
                }}
                className={`px-2.5 py-1 rounded-lg font-bold transition-colors cursor-pointer ${
                  activeTab === 'directory'
                    ? 'bg-[#0077b6] text-white shadow-2xs'
                    : 'text-[#03045e] hover:bg-[#caf0f8]'
                }`}
              >
                All Sections
              </button>
              <button
                onClick={() => {
                  setActiveTab('tour');
                  setIsTourActive(true);
                  handleTourStep(tourStepIdx);
                }}
                className={`px-2.5 py-1 rounded-lg font-bold transition-colors cursor-pointer flex items-center space-x-1 ${
                  activeTab === 'tour'
                    ? 'bg-[#0077b6] text-white shadow-2xs'
                    : 'text-[#03045e] hover:bg-[#caf0f8]'
                }`}
              >
                <Compass className="w-3 h-3" />
                <span>Guided Tour</span>
              </button>
              <button
                onClick={() => {
                  setActiveTab('ask');
                  setIsTourActive(false);
                }}
                className={`px-2.5 py-1 rounded-lg font-bold transition-colors cursor-pointer flex items-center space-x-1 ${
                  activeTab === 'ask'
                    ? 'bg-[#0077b6] text-white shadow-2xs'
                    : 'text-[#03045e] hover:bg-[#caf0f8]'
                }`}
              >
                <HelpCircle className="w-3 h-3" />
                <span>Ask AI</span>
              </button>
            </div>

            <button
              onClick={onOpenTrainingDocs}
              className="text-[11px] font-bold text-[#0077b6] hover:text-[#03045e] underline cursor-pointer"
            >
              Docs &amp; Exam &rarr;
            </button>
          </div>

          {/* Tab Content 1: Section Directory */}
          {activeTab === 'directory' && (
            <div className="flex-1 overflow-y-auto p-4 space-y-4 max-h-[460px]">
              <div className="text-xs text-stone-500 font-medium">
                Select any section below to get an instant breakdown and jump straight to that component:
              </div>

              {/* Section Select Chips */}
              <div className="grid grid-cols-2 gap-1.5">
                {SECTION_GUIDES.map((guide) => {
                  const Icon = guide.icon;
                  const isSelected = selectedSection?.id === guide.id;
                  return (
                    <button
                      key={guide.id}
                      onClick={() => setSelectedSection(guide)}
                      className={`text-left p-2 rounded-xl border text-xs transition-all cursor-pointer flex items-start space-x-2 ${
                        isSelected
                          ? 'bg-[#caf0f8] border-[#00b4d8] text-[#03045e] font-bold shadow-2xs'
                          : 'bg-stone-50 border-stone-200 text-stone-700 hover:bg-[#caf0f8]/30'
                      }`}
                    >
                      <Icon className={`w-3.5 h-3.5 mt-0.5 shrink-0 ${isSelected ? 'text-[#0077b6]' : 'text-stone-500'}`} />
                      <span className="truncate">{guide.title}</span>
                    </button>
                  );
                })}
              </div>

              {/* Selected Section Guide Detail Card */}
              {selectedSection && (
                <div className="p-4 rounded-xl bg-stone-50 border border-stone-200/90 space-y-3">
                  <div className="flex items-start justify-between">
                    <div>
                      <div className="text-xs font-bold text-[#0077b6] uppercase tracking-wider font-mono">
                        {selectedSection.view === 'model_studio' ? 'Probability Model Studio' : 'Market Contract Analyzer'}
                      </div>
                      <h4 className="text-sm font-black text-[#03045e] mt-0.5">
                        {selectedSection.title}
                      </h4>
                      <p className="text-[11px] text-stone-500 font-medium">{selectedSection.subtitle}</p>
                    </div>

                    <button
                      id="guide-jump-to-section-btn"
                      onClick={() => handleJumpToSection(selectedSection)}
                      className="inline-flex items-center space-x-1 px-3 py-1.5 rounded-lg text-xs font-bold bg-[#0077b6] text-white hover:bg-[#03045e] transition-colors shadow-2xs cursor-pointer shrink-0"
                    >
                      <span>Take Me There</span>
                      <ChevronRight className="w-3.5 h-3.5" />
                    </button>
                  </div>

                  <p className="text-xs text-stone-700 leading-relaxed">
                    {selectedSection.whatItDoes}
                  </p>

                  <div className="space-y-1.5 pt-1">
                    <div className="text-[11px] font-bold text-stone-500 uppercase tracking-wide">
                      Key Metrics To Understand:
                    </div>
                    {selectedSection.keyMetrics.map((km, idx) => (
                      <div key={idx} className="flex items-start space-x-1.5 text-xs text-stone-600">
                        <CheckCircle2 className="w-3.5 h-3.5 text-[#0077b6] shrink-0 mt-0.5" />
                        <span>{km}</span>
                      </div>
                    ))}
                  </div>

                  <div className="p-2.5 rounded-lg bg-[#caf0f8]/40 border border-[#90e0ef] text-[#03045e] text-xs flex items-start space-x-2">
                    <Lightbulb className="w-4 h-4 text-[#0077b6] shrink-0 mt-0.5" />
                    <div>
                      <span className="font-bold">Pro-Tip: </span>
                      <span>{selectedSection.proTip}</span>
                    </div>
                  </div>
                </div>
              )}
            </div>
          )}

          {/* Tab Content 2: Interactive Guided Tour */}
          {activeTab === 'tour' && (
            <div className="flex-1 overflow-y-auto p-4 space-y-4 max-h-[460px]">
              <div className="flex items-center justify-between text-xs">
                <span className="font-bold text-[#0077b6] font-mono uppercase tracking-wider">
                  Step {tourStepIdx + 1} of {TOUR_STEPS.length}
                </span>
                <span className="text-stone-400 font-medium">Interactive Walkthrough</span>
              </div>

              {/* Step Card */}
              <div className="p-4 rounded-xl bg-stone-50 border border-stone-200 space-y-3">
                <h4 className="text-base font-black text-[#03045e]">
                  {TOUR_STEPS[tourStepIdx].title}
                </h4>
                <p className="text-xs text-stone-700 leading-relaxed">
                  {TOUR_STEPS[tourStepIdx].description}
                </p>

                <div className="flex items-center space-x-2 pt-2">
                  <button
                    onClick={() => {
                      const step = TOUR_STEPS[tourStepIdx];
                      const el = document.getElementById(step.domId);
                      if (el) {
                        el.scrollIntoView({ behavior: 'smooth', block: 'center' });
                        el.classList.add('ring-4', 'ring-[#0077b6]', 'ring-offset-4');
                        setTimeout(() => el.classList.remove('ring-4', 'ring-[#0077b6]', 'ring-offset-4'), 2000);
                      }
                    }}
                    className="px-3 py-1.5 rounded-lg bg-[#03045e] text-white text-xs font-bold hover:bg-[#0077b6] transition-colors cursor-pointer"
                  >
                    Highlight on Screen
                  </button>
                </div>
              </div>

              {/* Tour Progress Navigation */}
              <div className="flex items-center justify-between pt-2 border-t border-stone-200">
                <button
                  disabled={tourStepIdx === 0}
                  onClick={() => handleTourStep(tourStepIdx - 1)}
                  className="px-3 py-1.5 rounded-lg border border-stone-300 text-xs font-semibold text-stone-700 hover:bg-stone-100 disabled:opacity-40 transition-colors cursor-pointer flex items-center space-x-1"
                >
                  <ChevronLeft className="w-3.5 h-3.5" />
                  <span>Previous</span>
                </button>

                <div className="flex items-center space-x-1">
                  {TOUR_STEPS.map((_, idx) => (
                    <button
                      key={idx}
                      onClick={() => handleTourStep(idx)}
                      className={`w-2 h-2 rounded-full transition-all cursor-pointer ${
                        idx === tourStepIdx ? 'w-5 bg-[#0077b6]' : 'bg-stone-300 hover:bg-stone-400'
                      }`}
                      aria-label={`Jump to tour step ${idx + 1}`}
                    />
                  ))}
                </div>

                <button
                  disabled={tourStepIdx === TOUR_STEPS.length - 1}
                  onClick={() => handleTourStep(tourStepIdx + 1)}
                  className="px-3 py-1.5 rounded-lg bg-[#0077b6] text-white text-xs font-bold hover:bg-[#03045e] disabled:opacity-40 transition-colors cursor-pointer flex items-center space-x-1 shadow-2xs"
                >
                  <span>Next Step</span>
                  <ChevronRight className="w-3.5 h-3.5" />
                </button>
              </div>
            </div>
          )}

          {/* Tab Content 3: Ask the Guide Bot (AI Chat) */}
          {activeTab === 'ask' && (
            <div className="flex-1 flex flex-col overflow-hidden max-h-[460px]">
              {/* Messages Container */}
              <div className="flex-1 overflow-y-auto p-4 space-y-3 text-xs">
                {chatMessages.map((msg) => (
                  <div
                    key={msg.id}
                    className={`flex flex-col ${msg.sender === 'user' ? 'items-end' : 'items-start'}`}
                  >
                    <div
                      className={`p-3 rounded-2xl max-w-[90%] leading-relaxed ${
                        msg.sender === 'user'
                          ? 'bg-[#0077b6] text-white rounded-br-xs'
                          : 'bg-stone-100 text-stone-900 rounded-bl-xs border border-stone-200'
                      }`}
                    >
                      <div className="whitespace-pre-line">{msg.text}</div>

                      {msg.suggestedAction && (
                        <div className="mt-2 pt-2 border-t border-stone-200/80">
                          <button
                            onClick={() => {
                              const guide = SECTION_GUIDES.find((g) => g.id === msg.suggestedAction?.sectionId);
                              if (guide) handleJumpToSection(guide);
                            }}
                            className="inline-flex items-center space-x-1 px-2.5 py-1 rounded-md bg-[#03045e] text-white text-[11px] font-bold hover:bg-[#0077b6] transition-colors cursor-pointer"
                          >
                            <span>{msg.suggestedAction.label}</span>
                            <ChevronRight className="w-3 h-3" />
                          </button>
                        </div>
                      )}
                    </div>
                  </div>
                ))}

                {isBotThinking && (
                  <div className="flex items-center space-x-2 text-stone-400 text-xs py-1">
                    <span className="w-2 h-2 rounded-full bg-[#0077b6] animate-bounce"></span>
                    <span className="w-2 h-2 rounded-full bg-[#0077b6] animate-bounce delay-100"></span>
                    <span className="w-2 h-2 rounded-full bg-[#0077b6] animate-bounce delay-200"></span>
                    <span className="text-[11px] font-mono">Guide Bot formulating answer...</span>
                  </div>
                )}
                <div ref={messagesEndRef} />
              </div>

              {/* Prompt Suggestion Chips */}
              <div className="px-4 py-2 bg-stone-50 border-t border-stone-200 flex items-center space-x-1.5 overflow-x-auto text-[11px]">
                <span className="text-stone-400 font-semibold shrink-0">Try:</span>
                {presetQuestions.map((q, idx) => (
                  <button
                    key={idx}
                    onClick={() => handleAskQuestion(q)}
                    className="px-2 py-1 rounded-md bg-white border border-stone-200 text-stone-700 hover:border-[#00b4d8] hover:text-[#03045e] shrink-0 transition-colors cursor-pointer"
                  >
                    {q}
                  </button>
                ))}
              </div>

              {/* Chat Input Bar */}
              <form
                onSubmit={(e) => {
                  e.preventDefault();
                  handleAskQuestion();
                }}
                className="p-3 bg-white border-t border-stone-200 flex items-center space-x-2"
              >
                <input
                  type="text"
                  value={inputQuestion}
                  onChange={(e) => setInputQuestion(e.target.value)}
                  placeholder="Ask anything about this app or prediction math..."
                  className="flex-1 px-3 py-2 rounded-xl border border-stone-300 text-xs focus:outline-none focus:ring-2 focus:ring-[#0077b6]"
                />
                <button
                  type="submit"
                  disabled={!inputQuestion.trim() || isBotThinking}
                  className="p-2 rounded-xl bg-[#0077b6] text-white hover:bg-[#03045e] disabled:opacity-40 transition-colors cursor-pointer shrink-0"
                  aria-label="Send message"
                >
                  <Send className="w-4 h-4" />
                </button>
              </form>
            </div>
          )}
        </div>
      )}
    </>
  );
};
