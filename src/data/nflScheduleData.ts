export function getMockNflScheduleResponse(filter?: string): NflScheduleResponse {
  let games = [...MOCK_NFL_SCHEDULE];

  if (filter && filter !== 'ALL') {
    const q = filter.toUpperCase();
    if (q === 'PRIMETIME') {
      games = games.filter((g) => g.isPrimetime);
    } else if (q.includes('NBC')) {
      games = games.filter((g) => g.broadcastNetwork.includes('NBC') || g.broadcastNetwork.includes('Peacock'));
    } else if (q.includes('CBS')) {
      games = games.filter((g) => g.broadcastNetwork.includes('CBS'));
    } else if (q.includes('FOX')) {
      games = games.filter((g) => g.broadcastNetwork.includes('FOX'));
    } else if (q.includes('ESPN')) {
      games = games.filter((g) => g.broadcastNetwork.includes('ESPN') || g.broadcastNetwork.includes('ABC'));
    } else if (q.includes('EARLY')) {
      games = games.filter((g) => g.timeSlot === 'Sunday Early');
    } else if (q.includes('LATE')) {
      games = games.filter((g) => g.timeSlot === 'Sunday Late');
    }
  }

  return {
    success: true,
    weekTitle: 'NFL Kickoff Week (Upcoming Slate)',
    seasonYear: '2024-2025 Regular Season',
    totalGames: games.length,
    lastUpdated: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' }),
    source: 'NFL Operations & League Broadcast Wire',
    games,
  };
}
