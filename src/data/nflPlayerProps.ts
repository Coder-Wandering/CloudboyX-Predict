/**
 * Returns line shift movement details relative to opening odds
 */
export function getPropLineMovement(prop: NflPlayerProp) {
  const openingLine = prop.openingLine ?? prop.consensusLine;
  const rawDelta = Number((prop.consensusLine - openingLine).toFixed(1));
  const direction: 'up' | 'down' | 'stable' =
    prop.lineMovement ?? (rawDelta > 0 ? 'up' : rawDelta < 0 ? 'down' : 'stable');
  const delta = prop.lineShiftDelta !== undefined ? prop.lineShiftDelta : rawDelta;
  const deltaFormatted = delta > 0 ? `+${delta}` : `${delta}`;

  return {
    direction,
    openingLine,
    delta,
    deltaFormatted,
    isShifted: direction !== 'stable',
    openingOdds: {
      over: prop.openingOverOdds || '-110',
      under: prop.openingUnderOdds || '-110',
    },
  };
}

